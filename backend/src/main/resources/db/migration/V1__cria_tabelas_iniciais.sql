CREATE TABLE transmissor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE aula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transmissor_id BIGINT NOT NULL REFERENCES transmissor(id),
    data_aula DATE NOT NULL,
    horario_inicio TIME NOT NULL,
    horario_fim TIME NOT NULL,
    sala VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA'
);

CREATE TABLE tipo_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    quantidade_disponivel INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE kit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL REFERENCES aula(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
);

CREATE TABLE kit_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id BIGINT NOT NULL REFERENCES kit(id),
    tipo_item_id BIGINT NOT NULL REFERENCES tipo_item(id),
    quantidade INTEGER NOT NULL
);

